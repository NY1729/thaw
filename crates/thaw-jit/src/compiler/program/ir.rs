#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
enum CompareOp {
    Less,
    LessEqual,
    Greater,
    GreaterEqual,
    Equal,
    NotEqual,
}

impl CompareOp {
    fn parse(operation: &str) -> Option<Self> {
        match operation {
            "lt" => Some(Self::Less),
            "lte" => Some(Self::LessEqual),
            "gt" => Some(Self::Greater),
            "gte" => Some(Self::GreaterEqual),
            "eq" => Some(Self::Equal),
            "ne" => Some(Self::NotEqual),
            _ => None,
        }
    }
}

