#!/usr/bin/env python3
"""Render the programs of tools/failure-conformance from the case table (cases.py).

usage: gen.py OUT_DIR [--chunk N] [--only SUBSTR]
Writes OUT_DIR/<group>.<n>.mts (Node) and .ts (thaw, identical text) plus manifest.json. Each program holds up to
N cases (default 40) in one switch; the case id is the last argv entry, so every case is its own process run.
Deterministic: same table, same bytes.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cases as table  # noqa: E402


def render(group, chunk):
    g = table.GROUPS[group]
    out = ["// generated by tools/failure-conformance/gen.py -- do not edit"]
    out += g["imports"]
    out.append(table.COMMON)
    out.append(g["prelude"])
    out.append("const caseId: string = process.argv[process.argv.length - 1];")
    out.append("switch (caseId) {")
    for c in chunk:
        out.append(f'case "{c["id"]}": {{\n{c["body"]}\nbreak;\n}}')
    out.append('default:\n  console.log("unknown case " + caseId);\n}')
    return "\n".join(out) + "\n"


def programs(chunk_size=40, only=""):
    progs = []
    for group, g in table.GROUPS.items():
        cs = [c for c in g["cases"] if only in c["id"]]
        for i in range(0, len(cs), chunk_size):
            progs.append({"name": f"{group}.{i // chunk_size}", "group": group, "cases": cs[i:i + chunk_size]})
    return progs


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--chunk", type=int, default=40)
    ap.add_argument("--only", default="")
    a = ap.parse_args(argv)
    os.makedirs(a.out, exist_ok=True)
    seen = set()
    manifest = {"programs": [], "cases": 0}
    for p in programs(a.chunk, a.only):
        text = render(p["group"], p["cases"])
        for ext in ("mts", "ts"):
            with open(os.path.join(a.out, f"{p['name']}.{ext}"), "w", encoding="utf-8") as fh:
                fh.write(text)
        for c in p["cases"]:
            assert c["id"] not in seen, f"duplicate case id {c['id']}"
            seen.add(c["id"])
        manifest["programs"].append({"name": p["name"], "group": p["group"], "cases": [
            {"id": c["id"], "mode": c.get("mode", "run"), "merge": bool(c.get("merge"))} for c in p["cases"]]})
        manifest["cases"] += len(p["cases"])
    with open(os.path.join(a.out, "manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=1)
    print(f"gen: {len(manifest['programs'])} programs, {manifest['cases']} cases")


if __name__ == "__main__":
    main(sys.argv[1:])
