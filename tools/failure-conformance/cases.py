"""The case table of tools/failure-conformance: one row per probe, grouped into programs.

C(group, id, body, **opts) appends a case. `body` is TypeScript placed in `case "<id>": { ... }` of the group's
program (the program takes the case id as its last argv entry, so each case is an independent process run).
opts: mode="run" (default) | "signal:SIGTERM" (the runner sends the
signal after the body printed READY) | "epipe" (the runner closes the read end of stdout after 1 byte);
merge=True sends stderr into the stdout pipe (ordering tests).
"""

