# Shared by the thaw and node copies. show() is deliberately plain: typeof, JSON for strings, element-wise
# arrays and typed arrays, own keys for plain objects, and [tag + constructor name] for everything else.
#
# PRELUDE is compiled into EVERY program: a compile reject of any API it calls rejects every probe and masks all
# findings (the first CI run did exactly that with ArrayBuffer.isView). Its probe-target API dependencies are
# declared in HELPER_DEPS; selftest.sh fails on any probe-target dotted API in PRELUDE that is not listed, and on
# a listed one that PRELUDE no longer mentions. The listed ones cannot be removed without changing the printed
# format. Array.isArray, JSON.stringify and Buffer.isBuffer precede ArrayBuffer.isView in show(), and the CI reject
# named only ArrayBuffer.isView, so the compiler accepts them. Object.keys is not yet confirmed by a CI run: if a
# red run rejects every probe, check it first.
HELPER_DEPS = ["Array.isArray", "Buffer.isBuffer", "JSON.stringify", "Object.keys"]
PRELUDE = r'''
function show(v: any, depth: number): string {
  if (v === undefined) { return "undefined"; }
  if (v === null) { return "null"; }
  const t: string = typeof v;
  if (t === "number") {
    if (v !== v) { return "number NaN"; }
    if (v === 0 && 1 / v < 0) { return "number -0"; }
    return "number " + String(v);
  }
  if (t === "string") { return "string " + JSON.stringify(v); }
  if (t === "boolean") { return "boolean " + String(v); }
  if (t === "bigint") { return "bigint " + String(v); }
  if (t === "symbol") { return "symbol"; }
  if (t === "function") { return "function"; }
  if (depth > 3) { return "deep"; }
  if (Array.isArray(v)) {
    let s: string = "array[";
    for (let i = 0; i < v.length && i < 50; i++) {
      s = s + (i > 0 ? "," : "") + show(v[i], depth + 1);
    }
    return s + "]";
  }
  const tag: string = Object.prototype.toString.call(v);
  // ponytail: typed-array test is BYTES_PER_ELEMENT (the isView probe target is avoided). Ceiling: a DataView,
  // or a plain object with an own BYTES_PER_ELEMENT key, prints differently. No probe produces either today.
  if (Buffer.isBuffer(v) || (tag !== "[object Object]" && v.BYTES_PER_ELEMENT !== undefined)) {
    let s: string = (Buffer.isBuffer(v) ? "Buffer " : "view ") + tag + " [";
    for (let i = 0; i < v.length && i < 50; i++) {
      s = s + (i > 0 ? "," : "") + show(v[i], depth + 1);
    }
    return s + "]";
  }
  if (tag === "[object Object]") {
    let s: string = "object {";
    const keys: string[] = Object.keys(v);
    for (let i = 0; i < keys.length && i < 50; i++) {
      s = s + (i > 0 ? "," : "") + keys[i] + ":" + show(v[keys[i]], depth + 1);
    }
    return s + "}";
  }
  const c: any = v.constructor;
  return "object " + tag + " ctor " + (typeof c === "function" ? String(c.name) : "none");
}

function p(name: string, f: () => any): void {
  console.log("@@ " + name);
  try {
    console.log(show(f(), 0));
  } catch (e: any) {
    console.log("THROW " + String(e.name) + ": " + String(e.message).split("\n").join(" "));
  }
}

function flip(): boolean { return true; }
function gen<T>(x: T): T { return x; }
function viaCb(x: any): any { return [x].map((y: any) => y)[0]; }
'''

