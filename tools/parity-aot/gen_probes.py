#!/usr/bin/env python3
"""Generate AOT-vs-Node probe programs (slice 1: Buffer/Uint8Array typing modes, Buffer statics, global ctors).

Output (OUT_DIR):
  lib.ts / lib.mts          module fixture for the `module` mode (thaw imports "./lib", node "./lib.mts")
  <family>.<mode>.cNN.ts    thaw copy: `function main(): void {...}`, thaw auto-invokes main (never call it here)
  <family>.<mode>.cNN.mts   node copy: same body plus `main();`
  manifest.json             programs, probes (name + one-line source), findings (list drift, op drift), counts

Every probe is ONE line `p("<name>", () => { <setup> return <expr>; });` so a compile diagnostic that names
a line maps back to exactly one probe (aot_run.py relies on this). A program holds at most PER_PROGRAM probes.
Expected output comes only from Node (aot_run.py); nothing here hard-codes an expectation.

List drift: the three ctor lists in crates/thaw-hir/src/lower/platform_globals.rs (PLATFORM_GLOBALS Ctor
entries, DYNAMIC_NEW_CTORS, DYNAMIC_OPAQUE_CTORS) are compared; differences are findings, not errors.
Method names used by the ops are checked against crates/thaw-js/src/builtin_table.tsv (OP-DRIFT).

Usage: gen_probes.py OUT_DIR [--per-program N]
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
TABLE = os.path.join(REPO, "crates", "thaw-js", "src", "builtin_table.tsv")
PLATFORM_RS = os.path.join(REPO, "crates", "thaw-hir", "src", "lower", "platform_globals.rs")
PER_PROGRAM = 40
LIB_SPEC = {"thaw": "./lib", "node": "./lib.mts"}

HEADER = "// Generated by tools/parity-aot/gen_probes.py. Do not edit by hand.\n"

# Shared by the thaw and node copies. show() is deliberately plain: typeof, JSON for strings, element-wise
# arrays and typed arrays, own keys for plain objects, and [tag + constructor name] for everything else.
PRELUDE = r'''
function show(v: any, depth: number): string {
  if (v === undefined) { return "undefined"; }
  if (v === null) { return "null"; }
  const t: string = typeof v;
  if (t === "number") {
    if (v !== v) { return "number NaN"; }
    if (v === 0 && 1 / v < 0) { return "number -0"; }
    return "number " + String(v);
  }
  if (t === "string") { return "string " + JSON.stringify(v); }
  if (t === "boolean") { return "boolean " + String(v); }
  if (t === "bigint") { return "bigint " + String(v); }
  if (t === "symbol") { return "symbol"; }
  if (t === "function") { return "function"; }
  if (depth > 3) { return "deep"; }
  if (Array.isArray(v)) {
    let s: string = "array[";
    for (let i = 0; i < v.length && i < 50; i++) {
      s = s + (i > 0 ? "," : "") + show(v[i], depth + 1);
    }
    return s + "]";
  }
  const tag: string = Object.prototype.toString.call(v);
  if (Buffer.isBuffer(v) || ArrayBuffer.isView(v)) {
    let s: string = (Buffer.isBuffer(v) ? "Buffer " : "view ") + tag + " [";
    for (let i = 0; i < v.length && i < 50; i++) {
      s = s + (i > 0 ? "," : "") + show(v[i], depth + 1);
    }
    return s + "]";
  }
  if (tag === "[object Object]") {
    let s: string = "object {";
    const keys: string[] = Object.keys(v);
    for (let i = 0; i < keys.length && i < 50; i++) {
      s = s + (i > 0 ? "," : "") + keys[i] + ":" + show(v[keys[i]], depth + 1);
    }
    return s + "}";
  }
  const c: any = v.constructor;
  return "object " + tag + " ctor " + (typeof c === "function" ? String(c.name) : "none");
}

function p(name: string, f: () => any): void {
  console.log("@@ " + name);
  try {
    console.log(show(f(), 0));
  } catch (e: any) {
    console.log("THROW " + String(e.name) + ": " + String(e.message).split("\n").join(" "));
  }
}

function flip(): boolean { return true; }
function gen<T>(x: T): T { return x; }
function viaCb(x: any): any { return [x].map((y: any) => y)[0]; }
'''

LIB_TS = """export function modBuffer(): Buffer { return Buffer.from([1, 2, 3, 250]); }
export function modU8(): Uint8Array { return new Uint8Array([1, 2, 3, 250]); }
"""

FAMILIES = {
    "buffer": {"T": "Buffer", "MK": "Buffer.from([1, 2, 3, 250])", "MOD": "modBuffer()",
               "DOC": "'{\"type\":\"Buffer\",\"data\":[1,2,3,250]}'"},
    "u8": {"T": "Uint8Array", "MK": "new Uint8Array([1, 2, 3, 250])", "MOD": "modU8()",
           "DOC": "'[1,2,3,250]'"},
}

# (op, expression template over {R}, usable in json mode). {R} is the mode's receiver expression.
OPS = [
    ("indexOf", "{R}.indexOf(2)", False),
    ("includes", "{R}.includes(250)", False),
    ("slice", "{R}.slice(1, 3)", False),
    ("subarray", "{R}.subarray(1)", False),
    ("fill", "{R}.fill(7, 1, 2)", False),
    ("set", "({R}.set([9, 9], 1), {R})", False),
    ("reverse", "{R}.reverse()", False),
    ("sort", "{R}.sort()", False),
    ("join", "{R}.join(\"-\")", False),
    ("toStringHex", "{R}.toString(\"hex\")", False),
    ("equalsBuf", "{R}.equals(Buffer.from([1, 2, 3, 250]))", False),
    ("readUInt8", "{R}.readUInt8(1)", False),
    ("swap16", "({R}.swap16(), {R})", False),
    ("indexGet", "{R}[1]", True),
    ("indexOob", "{R}[10]", True),
    ("indexNeg", "{R}[-1]", True),
    ("indexSet", "({R}[0] = 300, {R}[0])", False),
    ("length", "{R}.length", True),
    ("spread", "[...{R}]", True),
    ("forOf", "(() => { let s = 0; for (const x of {R}) { s += x; } return s; })()", True),
    ("destructure", "(() => { const [a, c] = {R}; return [a, c]; })()", True),
    ("inOp", "(2 in {R})", False),
    ("deleteIndex", "delete {R}[0]", False),
    ("typeofOp", "typeof {R}", True),
    ("instanceofU8", "{R} instanceof Uint8Array", False),
    ("instanceofBuffer", "{R} instanceof Buffer", False),
    ("stringOp", "String({R})", True),
    ("jsonStringify", "JSON.stringify({R})", True),
    ("isArray", "Array.isArray({R})", True),
    ("looseEqString", "{R} == \"1,2,3,250\"", False),
]

# Mode setup for the buffer/u8 families: (setup template, receiver expression). {T}/{MK}/{MOD}/{DOC} from FAMILIES.
MODES = {
    "typed": ("const b: {T} = {MK};", "b"),
    "any": ("const b: any = {MK};", "b"),
    "union": ("const b: {T} | null = flip() ? {MK} : null;", "(b as {T})"),
    "unknown": ("const u: unknown = {MK};", "(u as {T})"),
    "generic": ("const b = gen({MK});", "b"),
    "callback": ("const b: any = viaCb({MK});", "b"),
    "json": ("const b: any = JSON.parse({DOC});", "b"),
    "module": ("const b: {T} = {MOD};", "b"),
}

# Buffer statics. `x` is the mode's argument list (setup below).
STATIC_MODES = {
    "typed": "const x: Buffer[] = [Buffer.from([1]), Buffer.from([2, 3])];",
    "any": "const x: any = [Buffer.from([1]), 2];",
    "callback": "const x: any = viaCb([Buffer.from([1]), Buffer.from([2, 3])]);",
}
STATIC_OPS = [
    ("concat", "Buffer.concat(x)"),
    ("concatTotal", "Buffer.concat(x, 2).length"),
    ("isBufferElement", "Buffer.isBuffer(x[0])"),
    ("isBufferList", "Buffer.isBuffer(x)"),
    ("fromElement", "Buffer.from(x[1])"),
    ("fromList", "Buffer.from(x)"),
    ("allocFill", "Buffer.alloc(3, 1)"),
    ("allocNegative", "Buffer.alloc(-1)"),
    ("byteLength", "Buffer.byteLength(\"h\\u00e9llo\")"),
    ("compare", "Buffer.compare(x[0], x[1])"),
    ("isEncoding", "Buffer.isEncoding(\"utf8\")"),
    ("fromHex", "Buffer.from(\"616263\", \"hex\").toString()"),
    ("listLength", "x.length"),
    ("allocUnsafeZero", "Buffer.allocUnsafe(0).length"),
    ("fromU8", "Buffer.from(new Uint8Array([7, 8]))"),
    ("spreadList", "[...x]"),
]

# Constructor arguments for `new X(...)`; default is no arguments.
CTOR_ARGS = {
    "URL": "\"https://example.com/a?b=1\"",
    "URLSearchParams": "\"a=1&b=2\"",
    "Event": "\"tick\"",
    "CustomEvent": "\"tick\"",
    "DOMException": "\"msg\", \"AbortError\"",
    "Request": "\"https://example.com/\"",
    "Response": "\"hi\"",
    "Headers": "[[\"a\", \"1\"]]",
    "Blob": "[\"abc\"]",
    "File": "[\"abc\"], \"a.txt\"",
    "ByteLengthQueuingStrategy": "{ highWaterMark: 4 }",
    "CountQueuingStrategy": "{ highWaterMark: 4 }",
    "Buffer": "[1, 2]",
}

PROBE_LINE_RE = re.compile(r'^p\("([^"]+)", \(\) => \{ .* \}\);$')
METHOD_RE = re.compile(r"\{R\}\.(\w+)\(")
STATIC_METHOD_RE = re.compile(r"\bBuffer\.(\w+)\(")


def parse_platform(text):
    """(platform [(name, kind)], dynamic_new [name], dynamic_opaque [name]) from platform_globals.rs."""
    def section(marker):
        i = text.index(marker)
        return text[i:text.index("];", i)]
    platform = re.findall(r'\("(\w+)",\s*GlobalKind::(\w+)\)', section("pub const PLATFORM_GLOBALS"))
    new = re.findall(r'"(\w+)"', section("pub const DYNAMIC_NEW_CTORS"))
    opaque = re.findall(r'"(\w+)"', section("pub const DYNAMIC_OPAQUE_CTORS"))
    assert len(platform) > 50 and new and opaque, "platform_globals.rs parse came back short"
    return platform, new, opaque


def parse_table_keys(path):
    """Set of (owner, key) rows of builtin_table.tsv for the owners the ops call (Buffer, its prototype chain)."""
    keys = set()
    with open(path, encoding="utf-8") as fh:
        next(fh)
        for line in fh:
            cols = line.rstrip("\n").split("\t")
            if len(cols) > 1 and cols[0] in ("Buffer", "Buffer.prototype", "Uint8Array.prototype", "%TypedArray%.prototype"):
                keys.add((cols[0], cols[1]))
    assert keys, "builtin_table.tsv has no Buffer rows"
    return keys


def mode_setup(family, mode):
    fam = FAMILIES[family]
    setup, recv = MODES[mode]
    return setup.format(**fam), recv.format(T=fam["T"])


def build_probes():
    """[(family, mode, name, body, findings)] in emission order; body is the statements plus return."""
    probes = []
    for family in FAMILIES:
        for mode in MODES:
            setup, recv = mode_setup(family, mode)
            for op, tpl, json_ok in OPS:
                if mode == "json" and not json_ok:
                    continue
                probes.append((family, mode, f"{family}.{mode}.{op}", f"{setup} return {tpl.replace('{R}', recv)};"))
    for mode, setup in STATIC_MODES.items():
        for op, tpl in STATIC_OPS:
            probes.append(("static", mode, f"static.{mode}.{op}", f"{setup} return {tpl};"))
    return probes


def ctor_probes(ctors):
    out = []
    for name in ctors:
        args = CTOR_ARGS.get(name, "")
        out.append(("globals", "typed", f"globals.typed.new.{name}",
                    f"const o: {name} = new {name}({args}); return o;"))
        out.append(("globals", "any", f"globals.any.new.{name}",
                    f"const C: any = {name}; const o: any = new C({args}); return o;"))
        out.append(("globals", "any", f"globals.any.instanceof.{name}",
                    f"const C: any = {name}; const o: any = new C({args}); return o instanceof C;"))
        out.append(("globals", "any", f"globals.any.typeof.{name}",
                    f"const C: any = {name}; return [typeof C, String(C.name)];"))
    return out


def drift_findings(platform, new, opaque):
    ctors = [n for n, k in platform if k == "Ctor"]
    out = []
    for name in new:
        if name not in ctors:
            out.append(("LIST-DRIFT", f"DYNAMIC_NEW_CTORS `{name}` is not a Ctor in PLATFORM_GLOBALS"))
    for name in opaque:
        if name not in ctors:
            out.append(("LIST-DRIFT", f"DYNAMIC_OPAQUE_CTORS `{name}` is not a Ctor in PLATFORM_GLOBALS"))
    for name in ctors:
        if name not in new:
            out.append(("LIST-DRIFT", f"Ctor `{name}` is not in DYNAMIC_NEW_CTORS (new X() takes the pre-table arm)"))
        if name not in opaque:
            out.append(("LIST-DRIFT", f"Ctor `{name}` is not in DYNAMIC_OPAQUE_CTORS (annotation is not an opaque JsValue)"))
    return out, ctors


def op_findings(table):
    """OP-DRIFT: a method an op calls must exist on the Buffer prototype chain, or on Buffer itself for statics."""
    out = []
    for op, tpl, _ in OPS:
        m = METHOD_RE.search(tpl)
        if m and not any((owner, m.group(1)) in table
                         for owner in ("Buffer.prototype", "Uint8Array.prototype", "%TypedArray%.prototype")):
            out.append(("OP-DRIFT", f"op `{op}` calls `{m.group(1)}`, absent from builtin_table.tsv Buffer/%TypedArray% prototypes"))
    for op, tpl in STATIC_OPS:
        m = STATIC_METHOD_RE.search(tpl)
        if m and ("Buffer", m.group(1)) not in table:
            out.append(("OP-DRIFT", f"static op `{op}` calls `Buffer.{m.group(1)}`, absent from builtin_table.tsv"))
    return out


def render(lines, module, node):
    """Program text for the given probe lines (no indentation in `lines`)."""
    head = HEADER
    if module:
        head += f'import {{ modBuffer, modU8 }} from "{LIB_SPEC["node" if node else "thaw"]}";\n'
    text = head + PRELUDE + "\nfunction main(): void {\n"
    text += "".join("  " + line + "\n" for line in lines)
    text += "}\n"
    if node:
        text += "main();\n"
    return text


def chunk_programs(probes, per_program):
    """Group (family, mode, name, body) rows into programs of at most per_program probes, one family.mode each."""
    groups = {}
    order = []
    for family, mode, name, body in probes:
        key = (family, mode)
        if key not in groups:
            groups[key] = []
            order.append(key)
        groups[key].append((name, body))
    programs = []
    for key in order:
        family, mode = key
        rows = groups[key]
        for n, start in enumerate(range(0, len(rows), per_program)):
            chunk = rows[start:start + per_program]
            programs.append({
                "name": f"{family}.{mode}.c{n:02d}",
                "corpus": f"{family}.{mode}",
                "family": family,
                "mode": mode,
                "module": mode == "module",
                "probes": [{"name": name,
                            "line": f"p({json.dumps(name)}, () => {{ {body} }});"} for name, body in chunk],
            })
    return programs


def self_check(programs, per_program):
    names = []
    for prog in programs:
        assert len(prog["probes"]) <= per_program, prog["name"]
        for probe in prog["probes"]:
            assert PROBE_LINE_RE.match(probe["line"]), probe["line"]
            assert "\n" not in probe["line"] and " = " not in probe["name"]
            names.append(probe["name"])
    assert len(names) == len(set(names)), "duplicate probe names"
    return len(names)


def generate(out_dir, per_program=PER_PROGRAM):
    with open(PLATFORM_RS, encoding="utf-8") as fh:
        platform, new, opaque = parse_platform(fh.read())
    findings, ctors = drift_findings(platform, new, opaque)
    findings += op_findings(parse_table_keys(TABLE))
    probes = build_probes() + ctor_probes(ctors)
    programs = chunk_programs(probes, per_program)
    total = self_check(programs, per_program)
    for name in ctors:
        for mode in ("typed", "any"):
            assert any(p["name"] == f"globals.{mode}.new.{name}" for prog in programs for p in prog["probes"]), name
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "lib.ts"), "w", encoding="utf-8") as fh:
        fh.write(LIB_TS)
    with open(os.path.join(out_dir, "lib.mts"), "w", encoding="utf-8") as fh:
        fh.write(LIB_TS)
    for prog in programs:
        lines = [p["line"] for p in prog["probes"]]
        for suffix, node in ((".ts", False), (".mts", True)):
            with open(os.path.join(out_dir, prog["name"] + suffix), "w", encoding="utf-8") as fh:
                fh.write(render(lines, prog["module"], node))
    counts = {}
    for prog in programs:
        key = f"{prog['family']}.{prog['mode']}"
        counts[key] = counts.get(key, 0) + len(prog["probes"])
    manifest = {
        "per_program": per_program,
        "probes": total,
        "counts": counts,
        "findings": [{"class": c, "detail": d} for c, d in findings],
        "programs": programs,
    }
    with open(os.path.join(out_dir, "manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1, sort_keys=True)
        fh.write("\n")
    return manifest


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("out_dir")
    ap.add_argument("--per-program", type=int, default=PER_PROGRAM)
    args = ap.parse_args(argv)
    if args.per_program < 1:
        ap.error("--per-program must be >= 1")
    m = generate(args.out_dir, args.per_program)
    drift = [f for f in m["findings"] if f["class"] == "LIST-DRIFT"]
    print(f"probes: {m['probes']} in {len(m['programs'])} programs (<= {args.per_program} each)")
    for key, n in sorted(m["counts"].items()):
        print(f"  {key:<18}{n:>5}")
    print(f"findings: {len(m['findings'])} ({len(drift)} LIST-DRIFT, "
          f"{len(m['findings']) - len(drift)} OP-DRIFT)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
