#!/usr/bin/env python3
"""Generate AOT-vs-Node probe programs (slice 1: Buffer/Uint8Array typing modes, Buffer statics, global ctors).

Output (OUT_DIR):
  lib.ts / lib.mts          module fixture for the `module` mode (thaw imports "./lib", node "./lib.mts")
  <family>.<mode>.cNN.ts    thaw copy: `function main(): void {...}`, thaw auto-invokes main (never call it here)
  <family>.<mode>.cNN.mts   node copy: same body plus `main();`
  manifest.json             programs, probes (name + one-line source), findings (list drift, op drift), counts

Every probe is ONE line `p("<name>", () => { <setup> return <expr>; });` so a compile diagnostic that names
a line maps back to exactly one probe (aot_run.py relies on this). A program holds at most PER_PROGRAM probes.
Expected output comes only from Node (aot_run.py); nothing here hard-codes an expectation.

List drift: the three ctor lists in crates/thaw-hir/src/lower/platform_globals.rs (PLATFORM_GLOBALS Ctor
entries, DYNAMIC_NEW_CTORS, DYNAMIC_OPAQUE_CTORS) are compared; differences are findings, not errors.
Method names used by the ops are checked against crates/thaw-js/src/builtin_table.tsv (OP-DRIFT).

Slice 2 adds the built-in families (gen_builtins.py). Every probe row carries `api` (a list of API ids: table ids
`<owner>.<key>`, `global:<Name>` from node_globals.json, or documented `hand:` ids) and `mode`, both written to
manifest.json. Programs hold one (family, mode) each, sorted by api id, at most PER_PROGRAM probes.

Usage: gen_probes.py OUT_DIR [--per-program N] [--families a,b,c] [--max-probes N]
"""
