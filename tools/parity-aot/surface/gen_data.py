#!/usr/bin/env python3
"""Regenerate crates/thaw-registry/src/registry/builtins/surface_data.rs from real Node (22.x, pinned like inventory/).

The builtin JS modules carry hand-written, partial constant tables (os.constants.errno had 9 of 79 entries). This
dumps Node's own values for the plain-data exports listed in SPEC and the registry merges them into
`module.exports` after the module source runs (see builtins.rs `with_surface_data`). Never edit the .rs by hand.

Usage: gen_data.py [--check]     (--check: exit 1 when the committed file differs from what Node produces)
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../../../crates/thaw-registry/src/registry/builtins/surface_data.rs")
# module -> exports to dump; "*" = every top-level export whose value is a number or a string
SPEC = {
    "os": ["constants"],
    "http2": ["constants"],
    "zlib": ["constants"],
    "perf_hooks": ["constants"],
    "crypto": ["constants"],
    "module": ["constants"],
    "async_hooks": ["asyncWrapProviders"],
    "dns": ["*"],
    "dns/promises": ["*"],
    "process": ["config"],
}
JS = r"""
const spec = JSON.parse(process.argv[1]);
const plain = (v) => {
  if (typeof v === 'number' && !Number.isFinite(v)) return '@@' + String(v); // JSON has no Infinity/NaN; render() restores the literal
  if (typeof v === 'number' || typeof v === 'string' || typeof v === 'boolean') return v;
  if (Array.isArray(v)) return v.map(plain);
  if (v && typeof v === 'object') { const o = {}; for (const k of Object.getOwnPropertyNames(v).sort()) {
      const p = plain(v[k]); if (p !== undefined) o[k] = p; } return o; }
};
const out = {};
for (const [mod, names] of Object.entries(spec)) {
  const m = mod === 'process' ? process : require('node:' + mod); const o = {};
  for (const n of names) {
    if (n === '*') { for (const k of Object.keys(m).sort()) if (typeof m[k] === 'number' || typeof m[k] === 'string') o[k] = m[k]; }
    else if (m[n] !== undefined) o[n] = plain(m[n]);
  }
  out[mod] = o;
}
process.stdout.write(JSON.stringify(out));
"""


def render():
    raw = subprocess.run(["node", "-e", JS, json.dumps(SPEC)], check=True, capture_output=True, text=True).stdout
    data = json.loads(raw)
    def lit(v):
        t = json.dumps(v, sort_keys=True, separators=(",", ":"))
        for n in ("Infinity", "-Infinity", "NaN"):
            t = t.replace(f'"@@{n}"', n)
        return t
    arms = "".join(f'        "{m}" => Some(r####"{lit(v)}"####),\n' for m, v in sorted(data.items()))
    return ("// @generated by tools/parity-aot/surface/gen_data.py from Node's own values; do not edit.\n"
            "pub(super) fn data(module: &str) -> Option<&'static str> {\n    match module {\n" + arms + "        _ => None,\n    }\n}\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT).read() == text else 1)
    open(OUT, "w").write(text)
